// Writes src/lib/og/assets.generated.ts: the active preset's colours (src/styles/global.css) and the two static
// fonts the Open Graph images are drawn with (next/og reads woff and ttf, not woff2), embedded so the images can be
// drawn anywhere, also on hosts without a file system (Cloudflare Workers). Runs before `pnpm dev` and `pnpm build`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { firstFamily, presetPalette } from './palette.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
/** Static woff files for the preset fonts (Fontsource, SIL Open Font License). */
const STATIC_FONTS = {
  Literata: '@fontsource/literata/files/literata-latin-500-normal.woff',
  'Instrument Sans': '@fontsource/instrument-sans/files/instrument-sans-latin-500-normal.woff',
};
const font = (family) => (STATIC_FONTS[family] ? readFileSync(require.resolve(STATIC_FONTS[family])).toString('base64') : null);

const pal = presetPalette(undefined, root);
const c = pal.light;
const heading = font(firstFamily(c['font-heading'] ?? 'Literata')) ?? font('Literata');
const body = font(firstFamily(c['font-sans'] ?? 'Instrument Sans')) ?? heading;
const colours = Object.fromEntries(['background', 'foreground', 'muted-foreground', 'primary', 'border'].map((k) => [k, c[k]]));
const out = join(root, 'src/lib/og/assets.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by tools/og-assets.mjs from the preset "${pal.name}". Do not edit; it is rewritten before every dev and build.\nexport const preset = ${JSON.stringify(pal.name)};\nexport const colours = ${JSON.stringify(colours)} as const;\nexport const headingFont = ${JSON.stringify(heading)};\nexport const bodyFont = ${JSON.stringify(body)};\n`,
);
console.log(`og-assets: preset ${pal.name}`);
